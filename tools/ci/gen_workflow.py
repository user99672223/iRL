#!/usr/bin/env python3
"""Generate .github/workflows/build.yml from the pinned Madeira workflow.

Madeira's workflow assumes it is the repository root and runs on a private `xcode-27` runner.
iRL keeps Madeira as the `madeira/` submodule, so this rewrites it for that layout:
  * runs-on -> GitHub-hosted macos-26 (Xcode 26.6 / iOS 26.5 SDK; Madeira guards the two
    Xcode-27-only features, see REPORT.md)
  * every `run:` executes in madeira/, every cache/artifact path and hashFiles() argument gets
    the madeira/ prefix
  * checkout fetches iRL plus the madeira submodule (recursive only where Madeira's own did)
  * the app job applies tools/overlay/apply.sh before tools/build-ipa.sh, and uploads iRL.ipa
Re-run after moving the Madeira pin:  python3 tools/ci/gen_workflow.py
"""
import re, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
src = (ROOT / 'madeira/.github/workflows/build.yml').read_text()
P = 'madeira/'

out, in_path_block, path_indent = [], False, 0
for line in src.splitlines():
    s = line.strip()
    ind = len(line) - len(line.lstrip())
    if in_path_block:
        if s and ind > path_indent:
            neg = s.startswith('!')
            out.append(' ' * ind + ('!' if neg else '') + P + s.lstrip('!'))
            continue
        in_path_block = False
    m = re.match(r'^(\s*)path: (\|)?\s*(\S.*)?$', line)
    if m:
        if m.group(2):
            in_path_block, path_indent = True, len(m.group(1))
            out.append(line); continue
        val = m.group(3)
        out.append(f'{m.group(1)}path: {"!" if val.startswith("!") else ""}{P}{val.lstrip("!")}'); continue
    line = line.replace('runs-on: xcode-27', 'runs-on: macos-26')
    line = re.sub(r"hashFiles\(([^)]*)\)", lambda mm: 'hashFiles(' + re.sub(r"'([^']+)'", lambda q: f"'{P}{q.group(1)}'", mm.group(1)) + ')', line)
    line = line.replace('name: Madeira-ipa', 'name: iRL-ipa')
    out.append(line)
y = '\n'.join(out) + '\n'

# Checkout: iRL + madeira submodule.
y = re.sub(r'( *)- uses: actions/checkout@v4\n\1  with:\n\1    submodules: recursive\n',
           lambda m: f"{m.group(1)}- uses: actions/checkout@v4\n{m.group(1)}- run: git submodule update --init --recursive --depth 1 madeira\n{m.group(1)}  working-directory: .\n", y)
y = re.sub(r'( *)- uses: actions/checkout@v4\n(?! *- run: git submodule)',
           lambda m: f"{m.group(1)}- uses: actions/checkout@v4\n{m.group(1)}- run: git submodule update --init --depth 1 madeira\n{m.group(1)}  working-directory: .\n", y)
# All run: steps inside madeira/.
y = y.replace('\njobs:\n', '\ndefaults:\n  run:\n    working-directory: madeira\n\njobs:\n', 1)
y = y.replace('name: Build IPA\n', 'name: Build iRL IPA\n', 1)
# Overlay before the IPA build; publish under the iRL name too.
y = y.replace('      - name: Build IPA\n        run: tools/build-ipa.sh\n',
              '      - name: Apply iRL overlay\n        run: bash ../tools/overlay/apply.sh "$PWD"\n'
              '      - name: Build IPA\n        run: tools/build-ipa.sh && cp dist/Madeira.ipa dist/iRL.ipa\n', 1)
y = y.replace("branches: [main, 'codex/pr-build-*']", 'branches: [main]')
# The IPA cache must also change when the overlay changes: key it on iRL's tree (includes the pin).
y = y.replace("$(git rev-parse 'HEAD^{tree}')", "$(git -C .. rev-parse 'HEAD^{tree}')")
assert "git -C .. rev-parse 'HEAD^{tree}'" in y
hdr = '# GENERATED by tools/ci/gen_workflow.py from madeira/.github/workflows/build.yml. Do not edit.\n'
for need in ('Apply iRL overlay', 'working-directory: madeira', 'runs-on: macos-26'):
    assert need in y, need
assert 'xcode-27' not in y.replace('# xcode-27', '')
(ROOT / '.github/workflows/build.yml').write_text(hdr + y)
print('wrote .github/workflows/build.yml')
