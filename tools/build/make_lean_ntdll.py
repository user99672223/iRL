#!/usr/bin/env python3
"""Write madeira/build/ntdll-unix/build-irl.sh: Madeira's ntdll unix build without FFmpeg
(winegstreamer) and Vulkan (winevulkan), with irl_unixlib_stubs.c in their place (decision D5).

The derived script lives next to Madeira's (its BUILD_DIR is its own directory). Every edit is
asserted, so a Madeira pin that changes these lines fails here instead of building something else.
"""
import pathlib, re, sys
IRL = pathlib.Path(__file__).resolve().parents[2]
src = IRL / 'madeira/build/ntdll-unix/build.sh'
dst = src.with_name('build-irl.sh')
s = src.read_text()

def cut(text, start_pat, end_pat, what):
    a = text.find(start_pat)
    b = text.find(end_pat, a)
    assert a >= 0 and b > a, f'{what}: anchor not found'
    return text[:a] + f'# iRL: {what} removed (tools/build/make_lean_ntdll.py)\n' + text[b:]

# winevulkan unix side (two compile_unixlib calls)
s = cut(s, 'compile_unixlib "$WINE_SRC/dlls/winevulkan/vulkan.c"', '# iOS-Madeira 2026-08-03', 'winevulkan unix side')
# winegstreamer (FFmpeg + VideoToolbox) up to the ntdll source loop; the stub table goes there
stub = IRL / 'tools/build/irl_unixlib_stubs.c'
s = cut(s, 'FFMPEG_PREFIX=', 'for src in $WINE_SRC/dlls/ntdll/unix/*.c; do', 'winegstreamer unix side (FFmpeg)')
s = s.replace('for src in $WINE_SRC/dlls/ntdll/unix/*.c; do',
              f'compile_one "{stub}" "irl_unixlib_stubs"\n\nfor src in $WINE_SRC/dlls/ntdll/unix/*.c; do', 1)
n0 = len(s)
s = s.replace('"$OBJ_DIR/winevulkan_vulkan.o" "$OBJ_DIR/winevulkan_thunks.o" \\', '"$OBJ_DIR/irl_unixlib_stubs.o" \\', 1)
s = s.replace('    "$OBJ_DIR/winegstreamer_unixlib.o" "$OBJ_DIR/wg_parser_apple_ios.o" \\\n', '', 1)
assert len(s) < n0 and 'winegstreamer_unixlib.o' not in s and 'winevulkan_vulkan.o' not in s, 'ar list edit failed'
# Fail the build on any compile failure instead of letting ar trip over a missing object later.
s = s.replace('echo "=== Building libntdll_unix.a ==="', '[ "$FAILED" = 0 ] || { echo "iRL: $FAILED file(s) failed:$FAILED_FILES" >&2; for f in $FAILED_FILES; do cat "$OBJ_DIR/$f.err" >&2; done; exit 1; }\necho "=== Building libntdll_unix.a ==="', 1)
dst.write_text('# GENERATED by iRL tools/build/make_lean_ntdll.py from build.sh. Do not edit.\n' + s)
dst.chmod(0o755)
print(f'wrote {dst.relative_to(IRL)}')
